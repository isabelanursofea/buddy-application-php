session_start();
include "../database/dbconn.php";

// Check login
if (!isset($_SESSION['user_id'])) {
    header("Location: ../signin.php");
    exit();
}

$user_id = $_SESSION['user_id'];

// Get gender statistics
$sql = "SELECT gender, COUNT(*) AS count FROM friends WHERE user_id = ? GROUP BY gender";
$stmt = mysqli_prepare($conn, $sql);
mysqli_stmt_bind_param($stmt, "i", $user_id);
mysqli_stmt_execute($stmt);
$gender_result = mysqli_stmt_get_result($stmt);

$male_count = 0;
$female_count = 0;

while ($row = mysqli_fetch_assoc($gender_result)) {
    if ($row['gender'] == 'Male') $male_count = $row['count'];
    if ($row['gender'] == 'Female') $female_count = $row['count'];
}

// Get state statistics
$sql = "SELECT address4 AS state, COUNT(*) AS count FROM friends 
        WHERE user_id = ? AND address4 IS NOT NULL AND address4 != '' 
        GROUP BY address4 ORDER BY count DESC";
$stmt = mysqli_prepare($conn, $sql);
mysqli_stmt_bind_param($stmt, "i", $user_id);
mysqli_stmt_execute($stmt);
$state_result = mysqli_stmt_get_result($stmt);
$state_data = mysqli_fetch_all($state_result, MYSQLI_ASSOC);

// Get total friends
$sql = "SELECT COUNT(*) AS total FROM friends WHERE user_id = ?";
$stmt = mysqli_prepare($conn, $sql);
mysqli_stmt_bind_param($stmt, "i", $user_id);
mysqli_stmt_execute($stmt);
$result = mysqli_stmt_get_result($stmt);
$total_friends = mysqli_fetch_assoc($result)['total'];

// Generate PDF
if (isset($_GET['generate_pdf'])) {
    $report_type = $_GET['report_type'] ?? 'gender';
    
    require_once '../fpdf/fpdf.php';
    
    // Create PDF
    $pdf = new FPDF('P', 'mm', 'A4');
    $pdf->AddPage();
    
    // Set font
    $pdf->SetFont('Arial', 'B', 16);
    
    // Title
    $pdf->SetTextColor(63, 52, 36);
    $pdf->Cell(190, 10, 'Buddy Application Report', 0, 1, 'C');
    $pdf->SetFont('Arial', '', 12);
    $pdf->Cell(190, 8, 'Generated on: ' . date('d M Y, h:i A'), 0, 1, 'C');
    $pdf->Cell(190, 8, 'User: ' . $_SESSION['full_name'], 0, 1, 'C');
    $pdf->Ln(10);
    
    // Total Friends
    $pdf->SetFont('Arial', 'B', 14);
    $pdf->Cell(190, 10, 'Total Friends: ' . $total_friends, 0, 1, 'C');
    $pdf->Ln(5);
    
    if ($report_type == 'gender' || $report_type == 'full') {
        // Gender Report
        $pdf->SetFont('Arial', 'B', 14);
        $pdf->SetFillColor(242, 234, 220);
        $pdf->Cell(190, 10, 'Gender Distribution', 0, 1, 'L');
        
        $pdf->SetFont('Arial', 'B', 12);
        $pdf->SetFillColor(63, 52, 36);
        $pdf->SetTextColor(255, 255, 255);
        $pdf->Cell(95, 10, 'Gender', 1, 0, 'C', true);
        $pdf->Cell(95, 10, 'Count', 1, 1, 'C', true);
        
        $pdf->SetTextColor(0, 0, 0);
        $pdf->SetFont('Arial', '', 12);
        $pdf->SetFillColor(242, 234, 220);
        
        $pdf->Cell(95, 10, 'Male', 1, 0, 'C');
        $pdf->Cell(95, 10, $male_count, 1, 1, 'C');
        
        $pdf->Cell(95, 10, 'Female', 1, 0, 'C');
        $pdf->Cell(95, 10, $female_count, 1, 1, 'C');
        $pdf->Ln(10);
    }
    
    if ($report_type == 'state' || $report_type == 'full') {
        // State Report
        $pdf->SetFont('Arial', 'B', 14);
        $pdf->SetFillColor(242, 234, 220);
        $pdf->SetTextColor(0, 0, 0);
        $pdf->Cell(190, 10, 'Friends by State', 0, 1, 'L');
        
        $pdf->SetFont('Arial', 'B', 12);
        $pdf->SetFillColor(63, 52, 36);
        $pdf->SetTextColor(255, 255, 255);
        $pdf->Cell(95, 10, 'State', 1, 0, 'C', true);
        $pdf->Cell(95, 10, 'Count', 1, 1, 'C', true);
        
        $pdf->SetTextColor(0, 0, 0);
        $pdf->SetFont('Arial', '', 12);
        $pdf->SetFillColor(242, 234, 220);
        
        if (!empty($state_data)) {
            foreach ($state_data as $state) {
                $pdf->Cell(95, 10, $state['state'], 1, 0, 'C');
                $pdf->Cell(95, 10, $state['count'], 1, 1, 'C');
            }
        } else {
            $pdf->Cell(190, 10, 'No address data available', 1, 1, 'C');
        }
        $pdf->Ln(10);
    }
    
    // Footer
    $pdf->SetY(-15);
    $pdf->SetFont('Arial', 'I', 8);
    $pdf->SetTextColor(128, 128, 128);
    $pdf->Cell(0, 10, 'Generated by Buddy Application', 0, 0, 'C');
    
    // Output PDF
    $pdf->Output('D', 'buddy_report_' . $report_type . '.pdf');
    exit();
}
